	public static final int SIZE = 9;
	private final boolean[][] pixels;

	Icons(String... rows) {
		pixels = new boolean[SIZE][SIZE];
		for (int y = 0; y < SIZE; y++) {
			for (int x = 0; x < SIZE; x++) {
				pixels[y][x] = rows[y].charAt(x) == '#';
			}
		}
	}

	public void draw(GuiGraphicsExtractor g, int x, int y, int color) {
		draw(g, x, y, 1, color);
	}

	/** Draws the icon with its top-left at (x, y), each pixel {@code scale}×{@code scale}. */
	public void draw(GuiGraphicsExtractor g, int x, int y, int scale, int color) {
		for (int row = 0; row < SIZE; row++) {
			int col = 0;
			while (col < SIZE) {
				if (!pixels[row][col]) {
					col++;
					continue;
				}
				int start = col;
				while (col < SIZE && pixels[row][col]) {
					col++;
				}
				// One fill per horizontal run keeps this cheap.
				g.fill(x + start * scale, y + row * scale, x + col * scale, y + (row + 1) * scale, color);
			}
		}
	}

	/** The JavaHost logo: a green rounded tile with a "J". */
	public static void logo(GuiGraphicsExtractor g, int x, int y, int size) {
		Draw.roundRect(g, x, y, size, size, Math.max(2, size / 4), Theme.ACCENT);
		Draw.roundRect(g, x + 1, y + 1, size - 2, size / 2, Math.max(1, size / 4 - 1), Theme.withAlpha(0xFFFFFFFF, 0.12f));
		float scale = size / 12f;
		int glyph = Draw.font().width("J");
		Draw.scaledText(g, "J", Math.round(x + (size - glyph * scale) / 2f + scale * 0.5f), Math.round(y + (size - 8 * scale) / 2f + scale * 0.5f), scale, Theme.ON_ACCENT);
	}
