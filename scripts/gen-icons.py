#!/usr/bin/env python3
"""Turns Pixelarticons SVGs (MIT, https://github.com/halfmage/pixelarticons) into the pixel rows in Icons.java.

Usage: scripts/gen-icons.py <path to pixelarticons/svg>

Pixelarticons are drawn on a 24x24 pixel grid with straight, whole-pixel edges, so they rasterize exactly:
a pixel is set when its centre is inside the shape (non-zero winding). The script rewrites the block between
the GENERATED markers in Icons.java; everything else in that file is hand-written.
"""
import re
import sys
from pathlib import Path

GRID = 24
# Icons enum constant -> Pixelarticons name.
ICONS = {
    "HOME": "home", "HOST": "wifi", "JOIN": "login", "MIC": "mic", "MIC_OFF": "mic-off",
    "SPEAKER": "volume-2", "BOLT": "zap", "GEAR": "sliders", "COPY": "copy", "CHECK": "check",
    "CROSS": "close", "WARNING": "warning-diamond", "USER": "user", "USERS": "users", "GLOBE": "globe",
    "WIFI": "wifi", "PLAY": "play", "STOP": "stop", "PACKAGE": "package", "BELL": "bell", "CHAT": "message",
    "CAMERA": "image", "BACK": "arrow-left", "SEND": "send", "SPARKLE": "sparkles", "SHIRT": "shirt",
}
ICONS_JAVA = Path(__file__).resolve().parent.parent / "src/client/java/com/javahost/client/gui/ui/Icons.java"
BEGIN = "\t// GENERATED by scripts/gen-icons.py - do not edit by hand.\n"
END = "\t// END GENERATED\n"


def polygons(d):
    """Splits an SVG path made only of M/H/V/Z (absolute or relative) into closed polygons."""
    tokens = re.findall(r"[MmHhVvZzLl]|-?\d+(?:\.\d+)?", d)
    polys, current = [], []
    x = y = 0.0
    start = (0.0, 0.0)
    i = 0
    cmd = None
    while i < len(tokens):
        t = tokens[i]
        if re.match(r"[A-Za-z]", t):
            cmd = t
            i += 1
            if cmd in "Zz":
                if current:
                    polys.append(current)
                current = []
                x, y = start
            continue
        if cmd in "Mm":
            nx, ny = float(tokens[i]), float(tokens[i + 1])
            i += 2
            if cmd == "m":
                nx, ny = x + nx, y + ny
            if current:
                polys.append(current)
            x, y = nx, ny
            start = (x, y)
            current = [(x, y)]
            cmd = "l" if cmd == "m" else "L"  # extra pairs after a move are lines
        elif cmd in "Ll":
            nx, ny = float(tokens[i]), float(tokens[i + 1])
            i += 2
            if cmd == "l":
                nx, ny = x + nx, y + ny
            x, y = nx, ny
            current.append((x, y))
        elif cmd in "Hh":
            v = float(tokens[i])
            i += 1
            x = x + v if cmd == "h" else v
            current.append((x, y))
        elif cmd in "Vv":
            v = float(tokens[i])
            i += 1
            y = y + v if cmd == "v" else v
            current.append((x, y))
        else:
            raise ValueError(f"unsupported path command {cmd}")
    if current:
        polys.append(current)
    return polys


def winding(polys, px, py):
    total = 0
    for poly in polys:
        n = len(poly)
        for k in range(n):
            (x1, y1), (x2, y2) = poly[k], poly[(k + 1) % n]
            if y1 <= py < y2 or y2 <= py < y1:
                cross_x = x1 + (py - y1) * (x2 - x1) / (y2 - y1)
                if cross_x > px:
                    total += 1 if y2 > y1 else -1
    return total


def rasterize(svg_text):
    if re.search(r"<(rect|circle|ellipse|polygon|polyline|line)\b", svg_text):
        raise ValueError("only <path> elements are supported")
    polys = []
    for d in re.findall(r'\bd="([^"]+)"', svg_text):
        polys.extend(polygons(d))
    return ["".join("#" if winding(polys, x + 0.5, y + 0.5) != 0 else "." for x in range(GRID)) for y in range(GRID)]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    svg_dir = Path(sys.argv[1])
    out = [BEGIN]
    for i, (constant, name) in enumerate(ICONS.items()):
        rows = rasterize((svg_dir / f"{name}.svg").read_text())
        out.append(f"\t{constant}( // {name}\n")
        out.append(",\n".join(f'\t\t\t"{row}"' for row in rows))
        out.append(");\n" if i == len(ICONS) - 1 else "),\n")
    out.append(END)
    source = ICONS_JAVA.read_text()
    start, end = source.index(BEGIN), source.index(END) + len(END)
    ICONS_JAVA.write_text(source[:start] + "".join(out) + source[end:])
    print(f"wrote {len(ICONS)} icons to {ICONS_JAVA}")


if __name__ == "__main__":
    main()
